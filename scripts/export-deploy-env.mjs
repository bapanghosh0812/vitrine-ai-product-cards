#!/usr/bin/env node
/**
 * Local helper: writes ready-to-import env files for the hosting dashboards from .env.local.
 * The output files match `.env.*` in .gitignore, so they are never committed.
 * Prints key NAMES only, never values.
 *
 *   node scripts/export-deploy-env.mjs
 *
 * Writes:
 *   .env.vercel             import in Vercel  → Project → Settings → Environment Variables
 *   .env.netlify            import in Netlify → Site configuration → Environment variables
 *   .env.github-variables   values for GitHub → Settings → Secrets and variables → Actions → Variables
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { parseEnv } from 'node:util';

if (!existsSync('.env.local')) {
  console.error('.env.local not found. Run: node scripts/import-secrets.mjs ../_secrets');
  process.exit(1);
}
const local = parseEnv(readFileSync('.env.local', 'utf8'));

const PRIMARY = 'https://vitrine-ai-product-cards.vercel.app';
const PAGES_ORIGIN = 'https://bapanghosh0812.github.io';

const PUBLIC_KEYS = [
  'NG_APP_FIREBASE_API_KEY',
  'NG_APP_FIREBASE_AUTH_DOMAIN',
  'NG_APP_FIREBASE_PROJECT_ID',
  'NG_APP_FIREBASE_STORAGE_BUCKET',
  'NG_APP_FIREBASE_MESSAGING_SENDER_ID',
  'NG_APP_FIREBASE_APP_ID',
  'NG_APP_SUPPORT_EMAIL',
];
const SERVER_KEYS = ['GROQ_API_KEY', 'GEMINI_API_KEY', 'FIREBASE_PROJECT_ID', 'SMTP_USER', 'SMTP_PASS', 'SUPPORT_INBOX'];

const missing = [...PUBLIC_KEYS, ...SERVER_KEYS].filter((k) => !local[k]?.trim());
if (missing.length) console.warn(`warning: missing in .env.local: ${missing.join(', ')}`);

const pick = (keys) => Object.fromEntries(keys.filter((k) => local[k]?.trim()).map((k) => [k, local[k].trim()]));
const server = pick(SERVER_KEYS);
// Gmail shows app passwords in groups of four; the mailer strips spaces anyway.
if (server.SMTP_PASS) server.SMTP_PASS = server.SMTP_PASS.replace(/\s+/g, '');

const files = {
  '.env.vercel': {
    ...server,
    ...pick(PUBLIC_KEYS),
    NG_APP_SITE_URL: PRIMARY,
    SITE_URL: PRIMARY,
    // GitHub Pages calls the Vercel API from another origin.
    ALLOWED_ORIGINS: PAGES_ORIGIN,
  },
  '.env.netlify': {
    ...server,
    ...pick(PUBLIC_KEYS),
    NG_APP_SITE_URL: PRIMARY,
    SITE_URL: PRIMARY,
    AI_BUDGET_MS: '8500',
  },
  '.env.github-variables': pick(PUBLIC_KEYS),
};

const quote = (v) => (/[\s#"'=]/.test(v) ? JSON.stringify(v) : v);
for (const [file, values] of Object.entries(files)) {
  const body = Object.entries(values).map(([k, v]) => `${k}=${quote(v)}`).join('\n');
  writeFileSync(file, `# Generated by scripts/export-deploy-env.mjs. Gitignored. Never commit or share.\n${body}\n`);
  console.log(`${file}: ${Object.keys(values).join(', ')}`);
}
