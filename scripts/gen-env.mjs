#!/usr/bin/env node
/**
 * Writes src/environments/public-env.ts from environment variables (or .env.local).
 * Only PUBLIC values belong here: the Firebase web config is designed to be shipped to
 * browsers (access is enforced by Firestore rules), the rest are URLs and labels.
 * AI keys and the service account are never read by this script.
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { execSync } from 'node:child_process';
import { join } from 'node:path';

if (existsSync('.env.local') && !process.env.CI) process.loadEnvFile('.env.local');

const env = (name, fallback = '') => (process.env[name] ?? fallback).trim();

let commit = env('GITHUB_SHA') || env('VERCEL_GIT_COMMIT_SHA') || env('COMMIT_REF');
if (!commit) {
  try {
    commit = execSync('git rev-parse HEAD', { stdio: ['ignore', 'pipe', 'ignore'] }).toString().trim();
  } catch {
    commit = 'dev';
  }
}

const pkg = JSON.parse(readFileSync('package.json', 'utf8'));

const config = {
  firebase: {
    apiKey: env('NG_APP_FIREBASE_API_KEY'),
    authDomain: env('NG_APP_FIREBASE_AUTH_DOMAIN'),
    projectId: env('NG_APP_FIREBASE_PROJECT_ID'),
    storageBucket: env('NG_APP_FIREBASE_STORAGE_BUCKET'),
    messagingSenderId: env('NG_APP_FIREBASE_MESSAGING_SENDER_ID'),
    appId: env('NG_APP_FIREBASE_APP_ID'),
  },
  /** Empty = same origin. GitHub Pages builds point this at the Vercel deployment. */
  apiBase: env('NG_APP_API_BASE').replace(/\/+$/, ''),
  siteUrl: env('NG_APP_SITE_URL', 'https://vitrine-ai-product-cards.vercel.app').replace(/\/+$/, ''),
  repoUrl: env('NG_APP_REPO_URL', 'https://github.com/bapanghosh0812/vitrine-ai-product-cards'),
  supportEmail: env('NG_APP_SUPPORT_EMAIL'),
  version: pkg.version,
  commit: commit.slice(0, 7),
  builtAt: new Date().toISOString(),
};

const file = join('src', 'environments', 'public-env.ts');
mkdirSync(join('src', 'environments'), { recursive: true });
writeFileSync(
  file,
  `// AUTO-GENERATED by scripts/gen-env.mjs. Do not edit, do not commit (gitignored).\n` +
    `export const PUBLIC_ENV = ${JSON.stringify(config, null, 2)} as const;\n`,
);
const firebaseOn = Object.values(config.firebase).filter(Boolean).length >= 4;
console.log(`public env: firebase ${firebaseOn ? 'on' : 'off'}, api ${config.apiBase || 'same-origin'}, site ${config.siteUrl}`);
